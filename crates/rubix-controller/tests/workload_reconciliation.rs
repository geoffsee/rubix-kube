use std::net::IpAddr;
use std::sync::Arc;

use rubix_apiserver::{ApiserverConfig, ApiserverService, KubernetesStorage};
use rubix_controller::{ControllerManagerConfig, ControllerManagerService};
use rubix_datastore::{DatastoreConfig, DatastoreEngine};
use rubix_pki::cluster::{ClusterPki, ClusterPkiConfig};
use serde_json::json;
use tempfile::TempDir;

fn setup_test_controller(dir: &TempDir) -> ControllerManagerService {
    let node_ip: IpAddr = "192.0.2.1".parse().unwrap();
    let pki_dir = dir.path().join("pki");
    std::fs::create_dir_all(&pki_dir).unwrap();
    let datastore_dir = dir.path().join("datastore");

    let pki_config = ClusterPkiConfig::new(pki_dir.clone(), "test-node".to_string(), node_ip);
    let pki = ClusterPki::new(pki_config);
    pki.reconcile().expect("PKI reconcile");

    let (engine, _) = DatastoreEngine::open(DatastoreConfig::new(datastore_dir)).unwrap();
    let storage = KubernetesStorage::new(engine.client(), "/registry");

    let apiserver_config = ApiserverConfig::default_for_pki(&pki_dir, node_ip);
    let apiserver_service = ApiserverService::new(apiserver_config, storage);

    let controller_config = ControllerManagerConfig::default_for_pki(&pki_dir, node_ip);
    let apiserver_arc = Arc::new(apiserver_service);

    ControllerManagerService::new(controller_config, apiserver_arc)
}

#[tokio::test]
async fn test_deployment_and_replicaset_reconciliation_and_scaling() {
    let temp = TempDir::new().unwrap();
    let controller_svc = setup_test_controller(&temp);
    controller_svc.start().await.unwrap();

    let client = controller_svc.client();
    let wm = controller_svc.workload_manager();
    let ns = "test-deploy-ns";

    client.create_namespace(ns).await.unwrap();

    // 1. Create a Deployment with 3 replicas
    let deployment = json!({
        "apiVersion": "apps/v1",
        "kind": "Deployment",
        "metadata": {
            "name": "web-deploy",
            "namespace": ns
        },
        "spec": {
            "replicas": 3,
            "selector": {
                "matchLabels": { "app": "web" }
            },
            "template": {
                "metadata": {
                    "labels": { "app": "web" }
                },
                "spec": {
                    "containers": [{
                        "name": "nginx",
                        "image": "nginx:1.27"
                    }]
                }
            }
        }
    });

    client.create_deployment(ns, deployment).await.unwrap();

    // First reconciliation pass: Deployment -> ReplicaSet
    let summary1 = wm.reconcile_namespace(ns).await.unwrap();
    assert_eq!(summary1.deployments_reconciled, 1);
    assert_eq!(summary1.replicasets_reconciled, 1);

    // Verify child ReplicaSet exists and has owner reference pointing to Deployment
    let rs = client.get_replicaset(ns, "web-deploy-rs").await.unwrap();
    assert_eq!(rs["spec"]["replicas"], 3);
    let owner_refs = rs["metadata"]["ownerReferences"].as_array().unwrap();
    assert_eq!(owner_refs.len(), 1);
    assert_eq!(owner_refs[0]["kind"], "Deployment");
    assert_eq!(owner_refs[0]["name"], "web-deploy");

    // Second reconciliation pass: ReplicaSet -> Pods
    let summary2 = wm.reconcile_namespace(ns).await.unwrap();
    assert_eq!(summary2.deployments_reconciled, 1);
    assert_eq!(summary2.replicasets_reconciled, 1);

    let pod_list = client.list_pods(ns).await.unwrap();
    let pods = pod_list["items"].as_array().unwrap();
    assert_eq!(pods.len(), 3, "expected 3 pods generated by replicaset");

    for pod in pods {
        assert_eq!(
            pod["status"]["phase"], "Pending",
            "Pods must default to Pending phase without requiring a scheduler"
        );
        let pod_owners = pod["metadata"]["ownerReferences"].as_array().unwrap();
        assert_eq!(pod_owners[0]["kind"], "ReplicaSet");
        assert_eq!(pod_owners[0]["name"], "web-deploy-rs");
    }

    // 2. Scale Deployment up to 4
    let mut updated_dep = client.get_deployment(ns, "web-deploy").await.unwrap();
    updated_dep["spec"]["replicas"] = json!(4);
    client
        .update_deployment(ns, "web-deploy", updated_dep)
        .await
        .unwrap();

    let _ = wm.reconcile_namespace(ns).await.unwrap();
    let pod_list_scaled_up = client.list_pods(ns).await.unwrap();
    assert_eq!(pod_list_scaled_up["items"].as_array().unwrap().len(), 4);

    // 3. Scale Deployment down to 1
    let mut updated_dep_down = client.get_deployment(ns, "web-deploy").await.unwrap();
    updated_dep_down["spec"]["replicas"] = json!(1);
    client
        .update_deployment(ns, "web-deploy", updated_dep_down)
        .await
        .unwrap();

    let _ = wm.reconcile_namespace(ns).await.unwrap();
    let pod_list_scaled_down = client.list_pods(ns).await.unwrap();
    assert_eq!(pod_list_scaled_down["items"].as_array().unwrap().len(), 1);
}

#[tokio::test]
async fn test_statefulset_ordinal_pod_reconciliation() {
    let temp = TempDir::new().unwrap();
    let controller_svc = setup_test_controller(&temp);
    controller_svc.start().await.unwrap();

    let client = controller_svc.client();
    let wm = controller_svc.workload_manager();
    let ns = "test-ss-ns";

    client.create_namespace(ns).await.unwrap();

    let statefulset = json!({
        "apiVersion": "apps/v1",
        "kind": "StatefulSet",
        "metadata": {
            "name": "redis",
            "namespace": ns
        },
        "spec": {
            "replicas": 3,
            "template": {
                "metadata": {
                    "labels": { "app": "redis" }
                },
                "spec": {
                    "containers": [{ "name": "redis", "image": "redis:7" }]
                }
            }
        }
    });

    client.create_statefulset(ns, statefulset).await.unwrap();

    let _ = wm.reconcile_namespace(ns).await.unwrap();

    // Verify ordinal pods: redis-0, redis-1, redis-2
    for idx in 0..3 {
        let pod_name = format!("redis-{idx}");
        let pod = client
            .get_pod(ns, &pod_name)
            .await
            .expect("ordinal pod exists");
        assert_eq!(
            pod["metadata"]["labels"]["statefulset.kubernetes.io/pod-name"],
            pod_name
        );
        assert_eq!(
            pod["metadata"]["labels"]["apps.kubernetes.io/pod-index"],
            idx.to_string()
        );
        assert_eq!(pod["status"]["phase"], "Pending");
        let owners = pod["metadata"]["ownerReferences"].as_array().unwrap();
        assert_eq!(owners[0]["kind"], "StatefulSet");
        assert_eq!(owners[0]["name"], "redis");
    }

    // Scale down to 1: redis-1 and redis-2 should be removed
    let mut ss_scale = client.get_statefulset(ns, "redis").await.unwrap();
    ss_scale["spec"]["replicas"] = json!(1);
    client
        .update_statefulset(ns, "redis", ss_scale)
        .await
        .unwrap();

    let _ = wm.reconcile_namespace(ns).await.unwrap();

    assert!(client.get_pod(ns, "redis-0").await.is_ok());
    assert!(client.get_pod(ns, "redis-1").await.is_err());
    assert!(client.get_pod(ns, "redis-2").await.is_err());
}

