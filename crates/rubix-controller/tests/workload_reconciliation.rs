#[tokio::test]
async fn test_job_and_cronjob_reconciliation() {
    let temp = TempDir::new().unwrap();
    let controller_svc = setup_test_controller(&temp);
    controller_svc.start().await.unwrap();

    let client = controller_svc.client();
    let wm = controller_svc.workload_manager();
    let ns = "test-batch-ns";

    client.create_namespace(ns).await.unwrap();

    // 1. Reconcile standalone Job with parallelism = 2
    let job = json!({
        "apiVersion": "batch/v1",
        "kind": "Job",
        "metadata": {
            "name": "pi-job",
            "namespace": ns
        },
        "spec": {
            "parallelism": 2,
            "template": {
                "spec": {
                    "containers": [{ "name": "pi", "image": "perl" }]
                }
            }
        }
    });

    client.create_job(ns, job).await.unwrap();
    let _ = wm.reconcile_namespace(ns).await.unwrap();

    let pod0 = client
        .get_pod(ns, "pi-job-0")
        .await
        .expect("job pod 0 exists");
    let pod1 = client
        .get_pod(ns, "pi-job-1")
        .await
        .expect("job pod 1 exists");
    assert_eq!(pod0["metadata"]["labels"]["job-name"], "pi-job");
    assert_eq!(pod1["metadata"]["labels"]["job-name"], "pi-job");

    // 2. Reconcile CronJob
    let cronjob = json!({
        "apiVersion": "batch/v1",
        "kind": "CronJob",
        "metadata": {
            "name": "backup-cron",
            "namespace": ns
        },
        "spec": {
            "schedule": "*/5 * * * *",
            "jobTemplate": {
                "spec": {
                    "template": {
                        "spec": {
                            "containers": [{ "name": "backup", "image": "busybox" }]
                        }
                    }
                }
            }
        }
    });

    client.create_cronjob(ns, cronjob).await.unwrap();

    // Pass 1: CronJob -> child Job
    let _ = wm.reconcile_namespace(ns).await.unwrap();
    let child_job = client
        .get_job(ns, "backup-cron-scheduled")
        .await
        .expect("scheduled job exists");
    let cj_owners = child_job["metadata"]["ownerReferences"].as_array().unwrap();
    assert_eq!(cj_owners[0]["kind"], "CronJob");
    assert_eq!(cj_owners[0]["name"], "backup-cron");

    // Pass 2: Scheduled Job -> child Pod
    let _ = wm.reconcile_namespace(ns).await.unwrap();
    let cron_pod = client
        .get_pod(ns, "backup-cron-scheduled-0")
        .await
        .expect("cron job child pod exists");
    assert_eq!(cron_pod["status"]["phase"], "Pending");
}

#[tokio::test]
async fn test_garbage_collection_cascading_deletions() {
    let temp = TempDir::new().unwrap();
    let controller_svc = setup_test_controller(&temp);
    controller_svc.start().await.unwrap();

    let client = controller_svc.client();
    let wm = controller_svc.workload_manager();
    let ns = "test-gc-ns";

    client.create_namespace(ns).await.unwrap();

    // 1. Create Deployment, reconcile to produce ReplicaSet and Pods
    let deployment = json!({
        "apiVersion": "apps/v1",
        "kind": "Deployment",
        "metadata": { "name": "doomed-deploy", "namespace": ns },
        "spec": {
            "replicas": 2,
            "template": { "spec": { "containers": [{ "name": "app", "image": "nginx" }] } }
        }
    });
    client.create_deployment(ns, deployment).await.unwrap();
    let _ = wm.reconcile_namespace(ns).await.unwrap();
    let _ = wm.reconcile_namespace(ns).await.unwrap();

    assert!(client.get_replicaset(ns, "doomed-deploy-rs").await.is_ok());
    assert!(client.get_pod(ns, "doomed-deploy-rs-0").await.is_ok());
    assert!(client.get_pod(ns, "doomed-deploy-rs-1").await.is_ok());

    // 2. Delete parent Deployment and run reconciliation (which triggers GarbageCollector)
    client.delete_deployment(ns, "doomed-deploy").await.unwrap();
    let summary = wm.reconcile_namespace(ns).await.unwrap();

    assert!(
        summary.garbage_collected >= 3,
        "GC should have collected 1 ReplicaSet and 2 Pods"
    );
    assert!(client.get_replicaset(ns, "doomed-deploy-rs").await.is_err());
    assert!(client.get_pod(ns, "doomed-deploy-rs-0").await.is_err());
    assert!(client.get_pod(ns, "doomed-deploy-rs-1").await.is_err());
}

#[tokio::test]
async fn test_idempotence_and_restart_convergence() {
    let temp = TempDir::new().unwrap();
    let controller_svc = setup_test_controller(&temp);
    controller_svc.start().await.unwrap();

    let client = controller_svc.client();
    let wm1 = controller_svc.workload_manager();
    let ns = "test-idempotence-ns";

    client.create_namespace(ns).await.unwrap();

    // Create a Deployment with 2 replicas
    let deployment = json!({
        "apiVersion": "apps/v1",
        "kind": "Deployment",
        "metadata": { "name": "stable-deploy", "namespace": ns },
        "spec": {
            "replicas": 2,
            "template": { "spec": { "containers": [{ "name": "app", "image": "nginx" }] } }
        }
    });
    client.create_deployment(ns, deployment).await.unwrap();

    // Reconcile multiple times
    for _ in 0..5 {
        let _ = wm1.reconcile_namespace(ns).await.unwrap();
    }

    let pods = client.list_pods(ns).await.unwrap();
    assert_eq!(
        pods["items"].as_array().unwrap().len(),
        2,
        "repeated reconciliation loops must not produce duplicate pods"
    );

    // Simulate controller restart: fresh WorkloadManager
    let wm2 = controller_svc.workload_manager();
    for _ in 0..3 {
        let _ = wm2.reconcile_namespace(ns).await.unwrap();
    }

    let pods_after_restart = client.list_pods(ns).await.unwrap();
    assert_eq!(
        pods_after_restart["items"].as_array().unwrap().len(),
        2,
        "controller restart must converge without creating duplicate resources"
    );
}
